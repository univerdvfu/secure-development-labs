import os
import sqlite3
from pathlib import Path

import psycopg
from flask import current_app, g

SQLITE_SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id INTEGER PRIMARY KEY,
    username VARCHAR(80) UNIQUE NOT NULL,
    password VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL,
    role VARCHAR(30) NOT NULL,
    secret_note VARCHAR(240) NOT NULL
);
CREATE TABLE IF NOT EXISTS posts (
    id INTEGER PRIMARY KEY,
    title VARCHAR(160) NOT NULL,
    content TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS comments (
    id INTEGER PRIMARY KEY,
    author VARCHAR(80) NOT NULL,
    content TEXT NOT NULL
);
"""

USERS = [
    (1, "admin", "admin123", "admin@example.test", "admin", "Кодовая фраза: АДМИН-42"),
    (2, "student", "student123", "student@example.test", "student", "Личная заметка студента"),
    (3, "alice", "alice123", "alice@example.test", "student", "Номер зачётки: 103245"),
]

POSTS = [
    (1, "Безопасная разработка", "Учебный портал для анализа уязвимостей."),
    (2, "Правило лаборатории", "Проводите проверки только локально."),
]


def connect():
    database_url = os.getenv("DATABASE_URL")
    if database_url:
        return psycopg.connect(database_url)
    path = Path(current_app.config["DATABASE_PATH"])
    path.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(path)
    connection.row_factory = sqlite3.Row
    return connection


def get_db():
    if "db" not in g:
        g.db = connect()
    return g.db


def close_db(_error=None):
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()


def placeholder():
    return "%s" if os.getenv("DATABASE_URL") else "?"


def init_db():
    connection = connect()
    cursor = connection.cursor()
    schema = SQLITE_SCHEMA
    if os.getenv("DATABASE_URL"):
        schema = schema.replace(
            "id INTEGER PRIMARY KEY",
            "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
    if os.getenv("DATABASE_URL"):
        cursor.execute(schema)
        for user in USERS:
            cursor.execute(
                """
                INSERT INTO users (id, username, password, email, role, secret_note)
                VALUES (%s, %s, %s, %s, %s, %s)
                ON CONFLICT (id) DO NOTHING
                """,
                user,
            )
        for post in POSTS:
            cursor.execute(
                "INSERT INTO posts (id, title, content) VALUES (%s, %s, %s) ON CONFLICT (id) DO NOTHING",
                post,
            )
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('users', 'id'), (SELECT MAX(id) FROM users))"
        )
        cursor.execute(
            "SELECT setval(pg_get_serial_sequence('posts', 'id'), (SELECT MAX(id) FROM posts))"
        )
    else:
        connection.executescript(schema)
        cursor.executemany("INSERT OR IGNORE INTO users VALUES (?, ?, ?, ?, ?, ?)", USERS)
        cursor.executemany("INSERT OR IGNORE INTO posts VALUES (?, ?, ?)", POSTS)
    connection.commit()
    connection.close()


def init_app(app):
    app.teardown_appcontext(close_db)
    with app.app_context():
        init_db()
